                    <section id="accounts" aria-labelledby="accounts-title" tabindex="-1">
                        <p class="section-number">03 / YOUR ACCOUNT</p>
                        <h2 id="accounts-title">Accounts &amp; sign-in</h2>
                        <p>Email registration requests your first name, last name, email address, password, and locale. Our backend handles authentication and establishes an account session so you can use account features. Authentication credentials are used to verify access to your account.</p>
                        <h3>Sign in with Apple</h3>
                        <p>If you choose Sign in with Apple, Apple provides an identifier and, when available and authorized, your name and email address. You may choose Apple’s private email relay.</p>
                        <p>Our backend verifies Apple authentication and establishes a Quick Reads account session. Quick Reads does not receive your Apple Account password.</p>
                    </section>

                    <section id="reading" aria-labelledby="reading-title" tabindex="-1">
                        <p class="section-number">04 / TIME FOR A STORY</p>
                        <h2 id="reading-title">Reading, saved stories &amp; narration</h2>
                        <h3>On your device</h3>
                        <p>The app stores downloaded stories, reading and listening positions, reader preferences, private story reactions, and narration caches locally. Device backups may include this information, depending on your operating-system settings and backup services.</p>
                        <p>Explicit account favorites are also sent to our backend. Storing favorites does not mean your whole Library or reading and listening progress synchronizes across devices.</p>
                        <h3>Saved-story information &amp; guests</h3>
                        <p>For signed-in readers, we record which stories are saved and use that account-associated information to improve story suggestions.</p>
                        <p>Guests do not send reading-activity reports to us. Guest use still involves the search and content requests described below.</p>
                        <h3>Listening to narration</h3>
                        <p>Narration uses Apple’s system speech functionality and local audio caching. Quick Reads does not record the reader’s voice or upload microphone recordings for narration.</p>
                    </section>

                    <section id="service-requests" aria-labelledby="requests-title" tabindex="-1">
                        <p class="section-number">05 / FINDING YOUR NEXT READ</p>
                        <h2 id="requests-title">Search &amp; service requests</h2>
                        <p>When you search, the app sends your search terms and selected filters to our backend to return matching results. Browsing the catalog, opening or downloading a story, and loading artwork also involve network services.</p>
                        <p>These requests are separate from reading-activity reporting. Browsing, searching, and downloading involve network requests even when you use the app as a guest.</p>
                    </section>

                    <section id="sharing" aria-labelledby="sharing-title" tabindex="-1">
                        <p class="section-number">06 / SUPPORTING THE SERVICE</p>
                        <h2 id="sharing-title">Service providers &amp; sharing</h2>
                        <p>DigitalOcean hosts our database in the United States. Gandi provides email hosting for account-related messages and communications you send us. Information you send through these features is processed by the providers involved in delivering them.</p>
                        <p>If you choose Sign in with Apple, Apple supplies authentication information that our backend verifies. Apple also provides the operating-system speech functionality used for narration. Your device’s backup services may separately process local app information under your backup settings.</p>
                        <h3>Advertising</h3>
                        <p>Google Ads and its consent SDK have been removed from Quick Reads. The app has no AdMob or Firebase integration.</p>
                        <h3>In-app purchases</h3>
                        <p>Quick Reads no longer offers in-app purchases.</p>
                        <h3>This privacy webpage</h3>
                        <p>This page does not use analytics, advertising, tracking pixels, remotely loaded fonts, or cookies. Reading it does not require an account, a payment, or the app.</p>
                    </section>

                    <section id="storage" aria-labelledby="storage-title" tabindex="-1">
                        <p class="section-number">07 / WHERE INFORMATION LIVES</p>
                        <h2 id="storage-title">Storage, transfers &amp; retention</h2>
                        <p>Account information and explicit favorites are processed on the servers used to provide Quick Reads. Local reading information is stored on your device and may be included in device backups.</p>
                        <p>Our database is hosted by DigitalOcean in the United States. If you use Quick Reads from another country, information sent to that database is transferred to and processed in the United States.</p>
                        <p>Email is handled separately by Gandi. <a href="https://www.gandi.net/en/trust-center">Gandi lists infrastructure locations in France and Luxembourg</a>, so email services may involve processing in those countries. Your device and its backup services are governed separately by your operating-system settings.</p>
                        <p>Deleting your account removes the server account and associated account data. Local files and device backups have a separate lifecycle. Account deletion does not promise immediate removal of every backup copy or limited security record. See <a href="#delete-account">Delete your account</a> for what happens on your device.</p>
                    </section>

                    <section id="security" aria-labelledby="security-title" tabindex="-1">
                        <p class="section-number">08 / PROTECTING ACCESS</p>
                        <h2 id="security-title">Security</h2>
                        <p>Our backend verifies account credentials before establishing an authenticated session. Account deletion may require a recent sign-in to confirm that you control the account.</p>
                        <p>No method of storage or transmission can guarantee absolute security. Keep your sign-in credentials private and protect access to your device. If you suspect unauthorized access to your Quick Reads account, <a href="mailto:contact@leftlaneapps.com">contact us</a>.</p>
                    </section>

                    <section id="choices" aria-labelledby="choices-title" tabindex="-1">
                        <p class="section-number">09 / YOU HAVE A SAY</p>
                        <h2 id="choices-title">Your rights &amp; choices</h2>
                        <p>Depending on the law that applies to you, you may have rights to access or receive a copy of your personal information, correct it, request deletion, restrict or object to processing, or request portability. Where applicable, you may also raise a concern with the data protection authority where you live.</p>
                        <p>To make a privacy request, email <a href="mailto:contact@leftlaneapps.com?subject=Quick%20Reads%20privacy%20request">contact@leftlaneapps.com</a> and describe what you need. We may need information to verify your identity and locate the relevant records. Do not send your password.</p>
                        <p>If processing is based on your consent, you may withdraw that consent by contacting us. Withdrawal does not affect the lawfulness of processing carried out before you withdrew it.</p>
                        <p>You can manage device backups through your operating-system settings. Logging out ends a session; it does not delete your account or the local stories and reading information on your device.</p>
                    </section>

                    <section id="delete-account" aria-labelledby="deletion-title" tabindex="-1">
                        <p class="section-number">10 / LEAVING QUICK READS</p>
                        <h2 id="deletion-title">Delete your account</h2>
                        <div class="deletion-callout">
                            <span class="small-label">IN THE APP</span>
                            <p>Settings <span aria-hidden="true">→</span><span class="visually-hidden">then</span> <strong>Delete account</strong></p>
                            <span>Confirmation and a recent sign-in to the same account may be required.</span>
                        </div>
                        <p>Successful deletion removes your server account and its associated account data. Where Apple credentials have been retained for an account, the account-deletion process includes revoking them.</p>
                        <p><strong>Offline stories and local reading information remain on your device after account deletion.</strong> Logging out is separate from deleting an account. Neither action promises to remove every local file, backup, or security record immediately.</p>
                    </section>

